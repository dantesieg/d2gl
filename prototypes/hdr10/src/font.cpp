static const Glyph* find(char c) {
	c = (char)std::toupper((unsigned char)c);
	for (const Glyph& g : kGlyphs) if (g.c == c) return &g;
	return nullptr; // space / unknown -> blank
}

int font_draw(uint32_t* px, int w, int h, int x, int y, const char* s, uint32_t rgba, int scale) {
	int x0 = x;
	for (; *s; ++s, x += FONT_W * scale) {
		const Glyph* g = find(*s);
		if (!g) continue;
		for (int r = 0; r < 7; ++r)
			for (int c = 0; c < 5; ++c) {
				if (g->rows[r][c] != '#') continue;
				for (int sy = 0; sy < scale; ++sy)
					for (int sx = 0; sx < scale; ++sx) {
						int X = x + c * scale + sx, Y = y + r * scale + sy;
						if (X >= 0 && Y >= 0 && X < w && Y < h) px[Y * w + X] = rgba;
					}
			}
	}
	return x - x0;
}
